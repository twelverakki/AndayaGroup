/**
 * Real-time thousands separator formatter for currency & price inputs
 * Example: "10000" -> "10.000", "1500000" -> "1.500.000"
 */
export const formatNumberInput = (
	val: string | number | undefined | null,
): string => {
	if (val === undefined || val === null || val === "") return "";
	const cleanStr = String(val).replace(/\D/g, "");
	if (!cleanStr) return "";
	return new Intl.NumberFormat("id-ID").format(Number(cleanStr));
};

/**
 * Extracts raw numerical value from a thousands-formatted string
 * Example: "1.500.000" -> 1500000
 */
export const parseNumberInput = (
	val: string | number | undefined | null,
): number => {
	if (val === undefined || val === null || val === "") return 0;
	const cleanStr = String(val).replace(/\D/g, "");
	return cleanStr ? Number(cleanStr) : 0;
};
